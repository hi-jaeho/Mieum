CREATE DATABASE MIEUM;
USE MIEUM;

-- DEPARTMENT
CREATE TABLE DEPARTMENT (
	DEPARTMENT_ID INT PRIMARY KEY AUTO_INCREMENT    
    , DEPARTMENT_NAME VARCHAR(255) UNIQUE NOT NULL
);

-- POSITION
CREATE TABLE JOB_POSITION (
	POSITION_ID INT PRIMARY KEY AUTO_INCREMENT
    , POSITION_NAME VARCHAR(255) UNIQUE NOT NULL
);

-- EMPLOYEE
CREATE TABLE EMPLOYEE (
	EMPLOYEE_NO INT PRIMARY KEY AUTO_INCREMENT -- 사번
	, NAME VARCHAR(255) NOT NULL -- 이름
	, PASSWORD VARCHAR(255) NOT NULL -- 비밀번호
	, DEPARTMENT_ID INT  -- 부서ID
	, POSITION_ID INT -- 직책ID
	, EMAIL VARCHAR(255) NOT NULL UNIQUE -- 이메일
	, PHONE VARCHAR(255) NOT NULL UNIQUE -- 전화번호
	, ADDRESS VARCHAR(255) NOT NULL -- 주소
	, PROFILE_IMAGE_URL VARCHAR(255) -- 프로필 사진 주소(서버에 저장?)
	, STATUS_MESSAGE VARCHAR(255)  --  상태메시지
	, ROLE VARCHAR(255) DEFAULT 'USER' -- 역할(ADMIN, USER)
	, ACCOUNT_STATUS VARCHAR(255) DEFAULT 'ACTIVE' -- 계정 상태 -> 활성화, 비활성화(로그인 5회 실패), 탈퇴(퇴사) 처리 요청했는지, 탈퇴 되었는지(탈퇴 되어있는 경우 90일 이후 DB에서 삭제 처리 예정)
	, LOGIN_FAIL_COUNT INT DEFAULT 0 -- 로그인 실패 횟수
	, CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 계정 생성 일시
	, UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP -- 가장 최근 개인정보 수정 일시
	
	, FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENT(DEPARTMENT_ID)
	, FOREIGN KEY (POSITION_ID) REFERENCES JOB_POSITION(POSITION_ID)
);

-- PROFILE
CREATE TABLE PROFILE_CHANGE_REQUEST (
	REQUEST_ID INT PRIMARY KEY AUTO_INCREMENT -- 요청번호
	, EMPLOYEE_NO INT NOT NULL -- 요청한 사원의 사원번호
	, FIELD_NAME VARCHAR(255) NOT NULL --  필드이름(어떤 항목 수정을 요청했는지)
	, OLD_VALUE VARCHAR(255) -- 수정 이전의 값(혹시 몰라서 일단 넣었음. 굳이 안 넣어도 괜찮을지도?)
	, NEW_VALUE VARCHAR(255) NOT NULL -- 수정 이후의 값
	, REQUEST_STATUS VARCHAR(255) DEFAULT 'REQUESTED' CHECK (REQUEST_STATUS IN ('REQUESTED', 'APPROVED', 'REJECTED')) -- 요청의 현재 상태(요청 중, 승인, 거절 - 3개의 상태)
	, REQUESTED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 수정 요청 일시
	, PROCESSED_BY INT  -- 요청을 처리한 사원의 사원번호
	, PROCESSED_AT DATETIME -- 요청 처리한 일시
	, REASON VARCHAR(255) -- 거절 당했을 때 이유
	
	, FOREIGN KEY (EMPLOYEE_NO) REFERENCES EMPLOYEE(EMPLOYEE_NO)
	, FOREIGN KEY (PROCESSED_BY) REFERENCES EMPLOYEE(EMPLOYEE_NO)
);

CREATE TABLE PROFILE_IMAGE_LOG (
	LOG_ID INT PRIMARY KEY AUTO_INCREMENT -- 로그 ID
    , EMPLOYEE_NO INT -- 변경한 사원의 사원번호
    , OLD_IMAGE_URL VARCHAR(255) -- 변경 이전 프로필 사진의 주소(이것도 굳이 일지도?)
    , NEW_IMAGE_URL VARCHAR(255) -- 변경 이후 프로필 사진의 주소
    , CHANGED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 변경 일시
    
    , FOREIGN KEY (EMPLOYEE_NO) REFERENCES EMPLOYEE(EMPLOYEE_NO)
);

-- CUSTOMER
CREATE TABLE CUSTOMER (
	CUSTOMER_ID INT PRIMARY KEY AUTO_INCREMENT -- 고객의 DB에서의 부여번호
    , CUSTOMER_CODE VARCHAR(255) UNIQUE NOT NULL -- 사내에서의 고객의 고유번호(솔직히 쓸지 안쓸지 모르겠음)
    , LOGIN_ID VARCHAR(255) UNIQUE NOT NULL -- 고객의 로그인 시 사용할 ID
    , PASSWORD VARCHAR(255) NOT NULL -- 비밀번호
    , NAME VARCHAR(255) NOT NULL -- 고객의 이름
    , GENDER VARCHAR(2) NOT NULL CHECK (GENDER IN ('남', '여')) -- 성별
    , BIRTH_DATE DATE NOT NULL -- 생년월일
    , PHONE VARCHAR(255) UNIQUE NOT NULL -- 전화번호
	, EMAIL VARCHAR(255) NOT NULL -- 이메일
    , ADDRESS VARCHAR(255) NOT NULL -- 주소
    , OCCUPATION VARCHAR(255) NOT NULL -- 직업
    , HIGH_SCHOOL VARCHAR(255) -- 고등학교
	, UNIVERSITY VARCHAR(255) -- 대학
	, GRADUATE_SCHOOL VARCHAR(255) -- 대학원
    , INTRODUCTION TEXT -- 고객이 작성한 자기 소개
    , PREFERRED_PARTNER TEXT -- 고객이 원하는 이성상
    , CUSTOMER_STATUS VARCHAR(255) NOT NULL DEFAULT 'ACTIVE' -- 활성화 여부(우리 회사에서는 잠깐 결혼 활동을 쉬고 싶을 때 쉴 수 있게 처리할 수 있음)
    , MEMBERSHIP VARCHAR(255) NOT NULL -- 고객이 결제한 멤버쉽 플랜
	, PAID_AT DATETIME -- 고객이 결제하여 멤버쉽이 시작되는 일시
    , REGISTERED_BY INT NOT NULL -- 고객을 등록한 사원의 사원번호(여기서는 영업부 사원)
    , ASSIGNED_EMPLOYEE_NO INT -- 고객 매칭 등을 해줄 사원의 사원번호(여기서는 관리부 운영부 사원)
    , EMPLOYEE_COMMENT TEXT -- 직원이 평가한 고객 사항
    , CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 고객이 처음 상담을 진행한 일자
    , UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP -- 가장 마지막으로 정보를 수정한 일시
    
    ,FOREIGN KEY (REGISTERED_BY) REFERENCES EMPLOYEE(EMPLOYEE_NO)
    ,FOREIGN KEY (ASSIGNED_EMPLOYEE_NO) REFERENCES EMPLOYEE(EMPLOYEE_NO)
);

CREATE TABLE CUSTOMER_MATCHING_LOG(
	MATCHING_NO INT PRIMARY KEY AUTO_INCREMENT -- 매칭 번호
    , MANAGER_EMPLOYEE_NO INT NOT NULL -- 매칭을 진행한 사원의 사원번호
    , MALE_CUSTOMER_ID INT NOT NULL -- 매칭된 남성 고객의 고객번호
    , FEMALE_CUSTOMER_ID INT NOT NULL -- 매칭된 여성 고객의 고객번호
    , MATCHING_STATUS VARCHAR(20) NOT NULL DEFAULT 'PROPOSED' CHECK (MATCHING_STATUS IN ('PROPOSED', 'ACCEPTED' , 'REJECTED', 'MEETING', 'COMPLETED'))
    -- 매칭 상태(제안됨, 승인됨(둘 다 승인한 경우), 거절된(한 쪽 혹은 모두 거절한 경우), 만남(승인하여 만남 장소, 일시까지 정한 경우), 완료(실제로 만남이 성공하여 종료된 경우)
    , CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 매칭 제안하여 로그에 남긴 일시
    
    , FOREIGN KEY (MANAGER_EMPLOYEE_NO) REFERENCES EMPLOYEE(EMPLOYEE_NO)
    , FOREIGN KEY (MALE_CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
    , FOREIGN KEY (FEMALE_CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);

CREATE TABLE CUSTOMER_CONSULTATION (
	CONSULTATION_ID INT PRIMARY KEY AUTO_INCREMENT -- 상담 번호
    , CUSTOMER_ID INT NOT NULL -- 상담을 진행한 고객 번호
    , EMPLOYEE_NO INT NOT NULL -- 상담을 진행한 사원 번호
    , CONTENT TEXT NOT NULL -- 상담 내용
    , CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 상남 날짜
    
    , FOREIGN KEY (EMPLOYEE_NO) REFERENCES EMPLOYEE(EMPLOYEE_NO)
    , FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);

-- CHAT
CREATE TABLE CHAT_ROOM (
	CHAT_ROOM_ID INT PRIMARY KEY AUTO_INCREMENT -- 채팅방 번호
    , ROOM_TYPE VARCHAR(20) NOT NULL DEFAULT 'INTERNAL' CHECK (ROOM_TYPE IN ('INTERNAL', 'CUSTOMER')) -- 채팅방 타입(사원끼리 대화인지, 사원과 고객과의 대화인지)
    , CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 채팅방 생성 일시
);

CREATE TABLE CHAT_ROOM_MEMBER (
	CHAT_ROOM_MEMBER_ID INT PRIMARY KEY AUTO_INCREMENT -- 자동 부여 번호(의미 없음)
    , CHAT_ROOM_ID INT NOT NULL -- 채팅방 번호
    , MEMBER_TYPE VARCHAR(20) NOT NULL CHECK (MEMBER_TYPE IN ('EMPLOYEE', 'CUSTOMER')) -- 채팅방에 참여한 사람의 타입(직원인지 고객인지)
    , MEMBER_ID INT NOT NULL 
    , JOINED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 채팅방 참여 일시

    , FOREIGN KEY (CHAT_ROOM_ID) REFERENCES CHAT_ROOM(CHAT_ROOM_ID)
    , UNIQUE (CHAT_ROOM_ID, MEMBER_TYPE, MEMBER_ID) -- 같은 사람이 같은 채팅방에 2번 참여하는 것을 방지함
);

CREATE TABLE CHAT_MESSAGE (
	MESSAGE_ID INT PRIMARY KEY AUTO_INCREMENT -- 채팅 메시지 번호
    , CHAT_ROOM_ID INT NOT NULL -- 채팅방 번호
    , SENDER_TYPE VARCHAR(20) NOT NULL CHECK (MEMBER_TYPE IN ('EMPLOYEE', 'CUSTOMER')) -- 채팅방에 참여한 사람의 타입(직원인지 고객인지)
     -- 발신자 타입
    , SENDER_NO INT NOT NULL -- 발신자 번호(수신자는 딱히 필요 없음 -> 일대일이든 일대다이든 발신자가 아니면 모두 수신자이므로)
    , MESSAGE_TYPE VARCHAR(20) NOT NULL DEFAULT 'TEXT' CHECK (MESSAGE_TYPE IN ('TEXT', 'IMAGE', 'FILE')) -- 메세지가 어떤 타입인지
    , CONTENT TEXT -- 텍스트의 경우 내용
    , FILE_URL VARCHAR(255) -- 이미지나 파일이면 주소
    , CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP -- 보낸 일시
    
    , FOREIGN KEY (CHAT_ROOM_ID) REFERENCES CHAT_ROOM(CHAT_ROOM_ID)
);









